"""Export every audit summary row and deterministic manuscript tables."""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import shutil


def render(rows):
    def get(case, method, alternative=0, orientation='original'):
        row, = [r for r in rows if r['case'] == case and r['method'] == method
                and int(r['alternative']) == alternative and r['orientation'] == orientation]
        return row
    # Display whitening only as an identity, never silently hide unequal results.
    for alternative in (0, 1):
        for orientation in ('original', 'rotated'):
            pca = get('gaussian_balanced', 'canonical_pca', alternative, orientation)
            whiten = get('gaussian_balanced', 'canonical_whiten', alternative, orientation)
            for key in ('R', 'rejections', 'rate', 'lo95', 'hi95', 'se', 'mean_B_used'):
                assert pca[key] == whiten[key], (alternative, orientation, key)
    text = r'''% Generated by scripts/export_calibration_manuscript.py; do not edit numeric rows.
{\color{purple}
\subsection{Seeded implementation calibration and coupled representation audit}
\label{app:seeded-calibration}
This seeded local ARM64 cohort is the primary evidence for the calibration and
representation comparisons here, separate from the archived diagnostics. We retain
$\alpha=.05$, $d=20$, $K=4$, $B=100$, reference pseudocount $.1$, requested
$L=64$ and $d_{\rm sub}=1$; deduplication gives all twenty coordinate views.
The statistic is the sum of subspace $G$-tests. A shared reference batch per
view is reconstructed from fixed reference-role positions for every full ordered
permutation; all reference observations contribute to the reference histogram.
The same pooled Gaussian jitter field (SD $10^{-12}$), views and reference-position
randomness are coupled within each data block. The conservative reference uses
independent uniform permutations, the full fixed budget, and the plus-one tail.
Each other row changes only the named calibration switch. The row labeled
\emph{legacy-style combined} uses mid-$p$, antithetic pairs and Wilson stopping
in the corrected, seeded implementation. It recreates the calibration-option
combination, not a byte-for-byte rerun of every archived experiment.
All actual loops were executed.
Balanced samples have $N=M=500$; the rounded null rounds independent standard
Gaussian observations to integers before jitter. The other nulls are standard
Gaussian with the displayed unequal sizes.

There are $R=8000$ independent data blocks per null case. We use one-sided exact
binomial tests of over-rejection against $.05$ with the predeclared
Bonferroni family size 50 (including the unlaunched second cohort); pointwise
95\% intervals in Figure~\ref{fig:seeded-calibration} are not simultaneous intervals.
Missing cluster cohorts are not pooled: TU CPU pricing exceeded the aggregate
cap, and LRZ access was network-unreachable. Local Python 3.12.13, NumPy 2.5.2
and SciPy 1.18.1 define the completed software cohort.

\begin{table}[t]
\centering\small
\setlength{\tabcolsep}{8pt}\renewcommand{\arraystretch}{1.2}
\begin{tabular}{lrrrr}
\toprule
Calibration & Gaussian & Rounded & $(200,800)$ & $(800,200)$ \\
\midrule
'''
    cases = ['gaussian_balanced', 'rounded_balanced', 'gaussian_200_800', 'gaussian_800_200']
    for method, label in [('conservative','Independent plus-one'), ('midp_only','Mid-$p$ only'),
                          ('wilson_only','Wilson only'), ('antithetic_only','Antithetic only'),
                          ('legacy_combined','Legacy-style combined')]:
        cells=[]
        for case in cases:
            row=get(case,method)
            star=r'^{\dagger}' if float(row['p_over_bonf50']) < .05 else ''
            cells.append(f"${float(row['rate']):.5f}{star}$")
        text += label + ' & ' + ' & '.join(cells) + r' \\' + '\n'
    text += r'''\bottomrule
\end{tabular}
\caption{New seeded null rejection frequencies. $\dagger$ denotes significant
Bonferroni-50 over-rejection. All rows remain visible, including failures.}
\label{tab:seeded-calibration}
\end{table}

The legacy-style combined configuration over-rejects in all four cases, and mid-$p$
alone in three; the fourth adjusted $p$-value is $.06923$. Conservative sizes
range from $.04800$ to $.050875$, with no significant over-rejection in these
finite cases. This is supporting finite-case evidence, not proof of universal
calibration. Antithetic-only results here do not invalidate the separate
arithmetic counterexample to a general guarantee. Wilson-only binary decisions
match the fixed-budget decisions in all 32000 null blocks, although the mean
budget falls to about 55.5--55.7. This special threshold identity at $B=100$,
$\alpha=.05$, minimum check 50 and confidence-error parameter $.01$ is not a
validity theorem for arbitrary stopping settings or stopped $p$-values.
The archived rejection frequencies remain records of what those implementations
did, but they do not establish power superiority at a controlled 5\% level.
A more liberal test can reject more often under both nulls and alternatives;
matched comparisons at controlled size are required for a performance ranking.
The conservative audit improves calibration reliability, not necessarily the
rejection frequency under alternatives, and does not invalidate the rank
construction or establish the exact size error of every archived setting.

For the one-coordinate scale alternative (factor $1.5$), we additionally run
$R=500$ paired blocks. Pooled PCA is fitted in a new canonical row order before
transforming the points back to their original indices; this row-equivariant
fit is distinguished from the historical fitting order. Each representation
uses conservative calibration. Whitening and PCA are exactly equal in all
17000 checked null/power/orientation pairs, including observed scores,
$p$-values, decisions and permutation counts. This empirical identity includes
the actual post-transform fixed-scale jitter but does not prove its exact
rescaling equivariance on arbitrary inputs. Common pooled whitening positively
rescales PCA coordinates and hence adds no separate ideal coordinate-rank
improvement (Proposition~\ref{prop:pca-equivariance}). PCA mitigates the rotation
loss here, but its original-coordinate power is lower than the raw-coordinate
power ($.644$ versus $.724$); it is not universally preferable.

\begin{table}[t]
\centering\small
\setlength{\tabcolsep}{8pt}\renewcommand{\arraystretch}{1.2}
\begin{tabular}{lrrrr}
\toprule
Representation & Original power & Rotated power & Original size & Rotated size \\
\midrule
'''
    for method,label in [('conservative','Raw coordinates'),('canonical_pca',r'Pooled PCA$^{\ast}$')]:
        cells=[]
        for alt in (1,0):
            for orientation in ('original','rotated'):
                row=get('gaussian_balanced',method,alt,orientation)
                cells.append(f"${float(row['rate']):.4f}\\pm{float(row['se']):.4f}$")
        text += label+' & '+' & '.join(cells)+r' \\'+'\n'
    text += r'''\bottomrule
\end{tabular}
\caption{New coupled sparse-scale power ($R=500$) and Gaussian null size
($R=8000$), frequency $\pm$ binomial SE.
$\ast$~Whitening gives identical results: all 17000 paired scores, $p$-values,
decisions and budgets match, so no separate whitening row or independent evidence
is added. Exact pointwise power intervals appear in Figure~\ref{fig:coupled-rotation}.}
\label{tab:coupled-rotation}
\end{table}

\begin{figure}[t]
\centering\includegraphics[width=\linewidth]{calibration_audit.pdf}
\caption{Seeded null audit, pointwise exact 95\% intervals; red indicates
family-adjusted over-rejection. Auxiliary PCA/rotation null rows are retained
in the accompanying summary CSV and Table~\ref{tab:coupled-rotation}.}
\label{fig:seeded-calibration}
\end{figure}
\begin{figure}[t]
\centering\includegraphics[width=.8\linewidth]{coupled_rotation_audit.pdf}
\caption{Paired sparse-scale diagnostic under conservative calibration.
PCA mitigates this covariance-visible rotation failure, but does not give
samplewise rotation invariance or a remedy for arbitrary alternatives.}
\label{fig:coupled-rotation}
\end{figure}

The corrected source is frozen at tag \texttt{rank-calibration-20261004-source}
(numerical revision \texttt{04e3667}, wrapper revision \texttt{bd81b8a}).
The raw archive contains 203000 calls in 32500 complete blocks, with seeds,
input/configuration/source hashes and actual budgets; no failed/debug pilot
rows enter these tables. Wrapper-reserved local CPU cost is 5.457530 core-hours,
plus .021944 for the TU pilot; zero GPUs were allocated. The eight-core-hour
aggregate ceiling was not extended. Archived low-repetition power comparisons
remain diagnostics, not retrospectively validated calibrated rankings; the
new audit does not cover their different subspace/feature/sample settings.
}
'''
    return text


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--analysis',type=Path,required=True)
    parser.add_argument('--overleaf',type=Path,required=True)
    parser.add_argument('--images',type=Path,required=True)
    args=parser.parse_args()
    source=args.analysis/'summary.csv'
    audit=json.loads((args.analysis/'audit.json').read_text())
    assert audit['status']=='verified' and hashlib.sha256(source.read_bytes()).hexdigest()==audit['summary_sha256']
    assert audit['whitening_pairs'] == audit['whitening_equal_pairs'] == 17000
    rows=list(csv.DictReader(source.open()))
    assert len(rows)==31
    (args.overleaf/'empirical_calibration_audit.tex').write_text(render(rows))
    data=args.overleaf/'empirical_data/calibration_20261004'
    data.mkdir(parents=True,exist_ok=True)
    for name in ('summary.csv','audit.json'):
        shutil.copy2(args.analysis/name,data/name)
    for name in ('calibration_audit.pdf','coupled_rotation_audit.pdf'):
        shutil.copy2(args.images/name,args.overleaf/'imgs'/name)
    print('Exported all 31 summary rows, two generated tables and two figures.')


if __name__=='__main__':main()
